  String translate(String key, {Map<String, String>? params}) {
    String value = _localizedValues[locale.languageCode]?[key] ?? key;
    if (params != null) {
      params.forEach((k, v) {
        value = value.replaceAll('{$k}', v);
      });
    }
    return value;
  }

  String translateStatus(String status) {
    final normalized = status.trim().toLowerCase();
    if (normalized.isEmpty || normalized == 'not started') {
      return translate('not_started_status');
    }
    
    // Check for direct matches first
    final key = '${normalized.replaceAll(' ', '_')}_status';
    final translated = translate(key);
    
    if (translated != key) {
      return translated;
    }
    
    // Fallback if no specific translation exists
    return status;
  }

  bool get isRtl => locale.languageCode == 'ar';
}

class AppLocalizationsDelegate extends LocalizationsDelegate<AppLocalizations> {
  const AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) => ['en', 'ar'].contains(locale.languageCode);

  @override
  Future<AppLocalizations> load(Locale locale) async {
    return AppLocalizations(locale);
  }

  @override
  bool shouldReload(AppLocalizationsDelegate old) => false;
}
